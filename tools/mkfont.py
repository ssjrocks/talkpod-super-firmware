#!/usr/bin/env python3
"""Convert an X11 PCF bitmap font into a fixed-cell C font table for gfx.c.

usage: mkfont.py FONT.pcf[.gz] NAME FIRST LAST > gfx/NAME.c

The misc-fixed fonts in /usr/share/fonts/X11/misc are public domain. Each glyph is stored as
`h` rows of ceil(w / 8) bytes, most significant bit = leftmost pixel.
"""
import gzip
import sys

from PIL import PcfFontFile


def main():
    path, name, first, last = sys.argv[1], sys.argv[2], int(sys.argv[3], 0), int(sys.argv[4], 0)
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rb") as fp:
        pcf = PcfFontFile.PcfFontFile(fp)
    glyphs = {ch: g for ch, g in enumerate(pcf.glyph) if g}

    # dst box is (left, descent - ysize, left + xsize, descent), y up from the baseline
    ascent = max(-g[1][1] for g in glyphs.values())
    descent = max(g[1][3] for g in glyphs.values())
    w = max(g[0][0] for g in glyphs.values())
    h = ascent + descent
    stride = (w + 7) // 8

    out = []
    for ch in range(first, last + 1):
        rows = [0] * h
        g = glyphs.get(ch)
        if g:
            (left, top, _, _), im = g[1], g[3]
            px = im.load()
            for y in range(im.size[1]):
                for x in range(im.size[0]):
                    if px[x, y]:
                        cx, cy = left + x, ascent + top + y
                        if 0 <= cx < w and 0 <= cy < h:
                            rows[cy] |= 1 << (stride * 8 - 1 - cx)
        data = []
        for r in rows:
            data += [(r >> (8 * i)) & 0xFF for i in reversed(range(stride))]
        label = chr(ch) if ch != 0x5C else "backslash"
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data) + f",  /* {label} */")

    print(f"/* Generated by tools/mkfont.py from {path.rsplit('/', 1)[-1]} (X11 misc-fixed, public domain). */")
    print('#include "gfx.h"\n')
    print(f"static const uint8_t bits[] = {{")
    print("\n".join(out))
    print("};\n")
    print(f"const font_t {name} = {{ {w}, {h}, {stride}, 0x{first:02X}, 0x{last:02X}, bits }};")


if __name__ == "__main__":
    main()
