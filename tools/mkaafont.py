#!/usr/bin/env python3
"""Anti-aliased digit font (2 bits per pixel) for the big frequency display.

usage: mkaafont.py SIZE NAME > gfx/NAME.c

Renders '-' '.' '/' '0'-'9' from DejaVu Sans Bold (Bitstream Vera licence: free to embed) at SIZE
pixels. Glyphs share one height (the digits' extent); each has its own width (the advance). Pixels
are 0 = background .. 3 = full ink, packed 4 to a byte, leftmost pixel in the top bits.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
FIRST, LAST = 0x2D, 0x39        # '-' .. '9'


def main():
    size, name = int(sys.argv[1]), sys.argv[2]
    f = ImageFont.truetype(FONT, size)
    top = min(f.getbbox(c)[1] for c in "0123456789")
    bottom = max(f.getbbox(c)[3] for c in "0123456789")
    h = bottom - top
    widths, offsets, data = [], [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        w = round(f.getlength(ch))
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, -top), ch, font=f, fill=255)
        px = im.load()
        offsets.append(len(data))
        widths.append(w)
        for y in range(h):
            row = [round(px[x, y] / 255 * 3) for x in range(w)]
            row += [0] * (-len(row) % 4)
            for i in range(0, len(row), 4):
                data.append(row[i] << 6 | row[i + 1] << 4 | row[i + 2] << 2 | row[i + 3])

    print(f"/* Generated by tools/mkaafont.py {size} {name}: DejaVu Sans Bold (Bitstream Vera licence), */")
    print("/* 2 bits per pixel. */")
    print('#include "gfx.h"\n')
    print("static const uint8_t bits[] = {")
    for i in range(0, len(data), 16):
        print("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    print("};\n")
    print("static const uint8_t widths[] = {" + ", ".join(map(str, widths)) + "};")
    print("static const uint16_t offsets[] = {" + ", ".join(map(str, offsets)) + "};\n")
    print(f"const aafont_t {name} = {{ {h}, 0x{FIRST:02X}, 0x{LAST:02X}, widths, offsets, bits }};")


if __name__ == "__main__":
    main()
